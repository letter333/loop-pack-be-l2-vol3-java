-- =============================================================================
-- 상품 테이블 복합 인덱스 설계
-- 대상 테이블: products (100만 건)
-- 설계 원칙: 등호(=) 필터 → 정렬 컬럼 순서 배치 (B-Tree 활용 극대화)
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. 브랜드 필터 + 최신순 정렬
-- 근거: 브랜드 단독 필터 쿼리에서 brand_id 등호 필터 후
--       created_at DESC 정렬을 인덱스 순서로 처리하여 filesort 제거.
--       Zipf 분포: brand_id=1(28.5%, 285K건) ~ brand_id=80(0.14%, 1.4K건).
--       고카디널리티 브랜드에서는 정렬 인덱스 스캔+필터가 효율적이나,
--       저카디널리티 브랜드에서는 이 인덱스의 Lookup이 극적으로 효율적.
-- 커버: 브랜드+최신순, 브랜드+가격순(필터), 브랜드+좋아요순(필터),
--       브랜드+카테고리 조합(필터), 브랜드 COUNT
-- -----------------------------------------------------------------------------
CREATE INDEX idx_products_brand_created ON products (brand_id, created_at DESC);

-- -----------------------------------------------------------------------------
-- 2. 카테고리 필터 + 최신순 정렬
-- 근거: 카테고리 단독 필터(선택도 ~1.79%) 쿼리에서 category_id 등호 필터 후
--       created_at DESC 정렬을 인덱스 순서로 처리하여 filesort 제거.
--       카테고리+좋아요순 조합에서도 필터용으로 활용 (~17,875건 범위 축소).
-- 커버: 카테고리+최신순, 카테고리+좋아요순(필터), 카테고리 COUNT
-- -----------------------------------------------------------------------------
CREATE INDEX idx_products_category_created ON products (category_id, created_at DESC);

-- -----------------------------------------------------------------------------
-- 3. 좋아요순 정렬 (필터 없음)
-- 근거: 필터 없이 좋아요순 정렬 시 100만 건 filesort가 발생하여
--       OFFSET 850K에서 3.15초(최악 시나리오)까지 치솟는 문제 해결.
--       복합 정렬 (like_count DESC, created_at DESC) 순서를 인덱스로 커버.
-- 커버: 좋아요순 정렬 (OFFSET 낮은 구간에서 Index Scan 활용)
-- -----------------------------------------------------------------------------
CREATE INDEX idx_products_like_count ON products (like_count DESC, created_at DESC);

-- -----------------------------------------------------------------------------
-- 4. 가격순 정렬 (필터 없음)
-- 근거: 필터 없이 가격순 정렬 시 100만 건 filesort 발생.
--       base_price ASC 인덱스로 정렬 비용 제거.
--       브랜드+가격순 OFFSET 0에서도 Index Scan으로 활용 가능.
-- 커버: 가격순 정렬, 브랜드+가격순(OFFSET 0 — Index Scan + 필터)
-- -----------------------------------------------------------------------------
CREATE INDEX idx_products_base_price ON products (base_price ASC, created_at DESC);

-- -----------------------------------------------------------------------------
-- 5. 최신순 정렬 (필터 없음 — 기본 조회)
-- 근거: 가장 빈번한 기본 조회 쿼리에서 100만 건 filesort 제거.
--       created_at DESC 인덱스로 정렬 비용 완전 제거.
-- 커버: 필터 없음+최신순 (기본 페이지네이션)
-- -----------------------------------------------------------------------------
CREATE INDEX idx_products_created ON products (created_at DESC);
